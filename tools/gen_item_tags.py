#!/usr/bin/env python3
"""Generates crates/zomboid-engine/src/zombie/scripting/objects/item_tag_table.rs from the decompiled
zombie.scripting.objects.ItemTag: the ids its static initialiser registers with `registerBase("Id")` into
`Registries.ITEM_TAG`, in declaration order (the vanilla registry; nothing else registers item tags in the game).
  python3 tools/gen_item_tags.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "decompiled/zombie/scripting/objects/ItemTag.java").read_text()
ids = re.findall(r'^   public static final ItemTag \w+ = registerBase\("([^"]+)"\);$', src, re.M)
if not ids or len(set(i.lower() for i in ids)) != len(ids):
    raise SystemExit("unexpected ItemTag.java")
out = root / "crates/zomboid-engine/src/zombie/scripting/objects/item_tag_table.rs"
lines = ["//! Generated by tools/gen_item_tags.py from zombie.scripting.objects.ItemTag. Do not edit.", "",
         "/// The ids `ItemTag.registerBase` registers in the namespace \"base\", in declaration order.",
         "#[rustfmt::skip]", "pub const BASE_IDS: [&str; %d] = [" % len(ids)]
lines += ['    "%s",' % i for i in ids]
lines += ["];", ""]
out.write_text("\n".join(lines))
print("%s: %d item tags" % (out.relative_to(root), len(ids)))
