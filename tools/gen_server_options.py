#!/usr/bin/env python3
"""Generates crates/zomboid-engine/src/zombie/network/server_options_table.rs from the decompiled
zombie.network.ServerOptions: every option in registration order (field order).
  python3 tools/gen_server_options.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "decompiled/zombie/network/ServerOptions.java").read_text()
CALL = re.compile(r'new ServerOptions\.(Boolean|Double|Enum|Integer|String|Text)ServerOption\(\s*this,\s*"([^"]+)",\s*(.*?)\);\n', re.S)
def num(s):
    return s.strip().replace("Integer.MAX_VALUE", "2147483647").replace("Integer.MIN_VALUE", "-2147483648")
def rust_str(lit):
    # a Java string literal is a Rust one for the escapes the file uses (\\ \" \n)
    assert re.fullmatch(r'"(?:[^"\\]|\\[\\"n])*"', lit), lit
    return lit
rows = []
for m in CALL.finditer(src):
    kind, name, args = m.group(1), m.group(2), m.group(3)
    if kind in ("String", "Text"):
        lit = re.match(r'\s*(.*?)\s*,\s*(-?\d+)\s*$', args, re.S)
        default, max_length = lit.group(1), lit.group(2)
        if default == "GameServer.seed":
            # GameServer.seed: "" until GameServer.main sets it (a client never does)
            d = 'Default::Str("")'
        elif r := re.fullmatch(r'Integer\.toString\(Rand\.Next\((.*)\)\)', default):
            d = "Default::RandString(%s)" % num(r.group(1))
        else:
            d = "Default::Str(%s)" % rust_str(default)
        k = "Kind::Text" if kind == "Text" else "Kind::Str"
        rows.append('    Def { name: "%s", kind: %s { default: %s, max_length: %s } },' % (name, k, d, max_length))
        continue
    a = [x.strip() for x in args.split(",")]
    if kind == "Boolean":
        rows.append('    Def { name: "%s", kind: Kind::Boolean(%s) },' % (name, a[0]))
    elif kind == "Double":
        f = lambda x: x if any(c in x for c in ".eE") else x + ".0"
        rows.append('    Def { name: "%s", kind: Kind::Double { min: %s, max: %s, default: %s } },' % (name, f(a[0]), f(a[1]), f(a[2])))
    elif kind == "Integer":
        if r := re.fullmatch(r'Rand\.Next\((.*)\)', a[2]):
            d = "Default::Rand(%s)" % num(r.group(1))
        else:
            d = "Default::Int(%s)" % num(a[2])
        rows.append('    Def { name: "%s", kind: Kind::Integer { min: %s, max: %s, default: %s } },' % (name, num(a[0]), num(a[1]), d))
    elif kind == "Enum":
        rows.append('    Def { name: "%s", kind: Kind::Enum { num_values: %s, default: %s } },' % (name, num(a[0]), num(a[1])))
out = ("//! Generated by tools/gen_server_options.py from zombie.network.ServerOptions (registration order). Do not edit.\n"
       "use super::server_options::{Def, Default, Kind};\n\npub static OPTIONS: [Def; %d] = [\n%s\n];\n" % (len(rows), "\n".join(rows)))
(root / "crates/zomboid-engine/src/zombie/network/server_options_table.rs").write_text(out)
print(len(rows), "options")
