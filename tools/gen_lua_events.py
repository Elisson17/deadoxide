#!/usr/bin/env python3
"""Generates crates/zomboid-engine/src/zombie/lua/lua_events_table.rs from the decompiled zombie.Lua.LuaEventManager
and zombie.Lua.LuaHookManager: the names their AddEvents() register, in order.
  python3 tools/gen_lua_events.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
def names(cls):
    src = (root / f"decompiled/zombie/Lua/{cls}.java").read_text()
    i = src.index("private static void AddEvents() {")
    j = src.index("\n   }\n", i)
    return re.findall(r'AddEvent\("([^"]+)"\);', src[i:j])
events, hooks = names("LuaEventManager"), names("LuaHookManager")
out = ["//! Generated by tools/gen_lua_events.py from zombie.Lua.LuaEventManager / LuaHookManager.AddEvents. Do not edit.", ""]
for const, doc, items in (("EVENTS", "LuaEventManager.AddEvents", events), ("HOOKS", "LuaHookManager.AddEvents", hooks)):
    out.append(f"/// {doc}, in registration order.")
    out.append(f"pub const {const}: [&str; {len(items)}] = [")
    out += [f'    "{n}",' for n in items]
    out.append("];")
    out.append("")
(root / "crates/zomboid-engine/src/zombie/lua").mkdir(parents=True, exist_ok=True)
(root / "crates/zomboid-engine/src/zombie/lua/lua_events_table.rs").write_text("\n".join(out))
print(len(events), "events,", len(hooks), "hooks")
